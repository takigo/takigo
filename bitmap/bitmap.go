// Package bitmap provides Tk's built-in XBM bitmaps (error, gray12, gray25,
// gray50, gray75, hourglass, info, questhead, question, warning).
package bitmap

import (
	goimage "image"
	gocolor "image/color"
	"os"
	"strconv"
	"strings"

	tkimage "github.com/msorc/takigo/image"
)

// Get returns a Photo for the named built-in bitmap with the given foreground
// and background colors. Returns nil if the name is unknown.
func Get(name string, fg, bg gocolor.RGBA) *tkimage.Photo {
	src, ok := builtins[name]
	if !ok {
		return nil
	}
	w, h, bits := parseXBM(src)
	if w == 0 || h == 0 {
		return nil
	}
	rowBytes := (w + 7) / 8
	rgba := goimage.NewRGBA(goimage.Rect(0, 0, w, h))
	for row := range h {
		for col := range w {
			byteIdx := row*rowBytes + col/8
			bit := (bits[byteIdx] >> uint(col%8)) & 1
			if bit == 1 {
				rgba.SetRGBA(col, row, fg)
			} else {
				rgba.SetRGBA(col, row, bg)
			}
		}
	}
	return tkimage.NewPhoto("bitmap:"+name, rgba)
}

func parseXBM(src string) (w, h int, bits []byte) {
	for line := range strings.SplitSeq(src, "\n") {
		line = strings.TrimSpace(line)
		if !strings.HasPrefix(line, "#define") {
			continue
		}
		fields := strings.Fields(line)
		if len(fields) < 3 {
			continue
		}
		val, err := strconv.Atoi(fields[2])
		if err != nil {
			continue
		}
		if strings.HasSuffix(fields[1], "_width") {
			w = val
		} else if strings.HasSuffix(fields[1], "_height") {
			h = val
		}
	}

	_, rest, ok := strings.Cut(src, "{")
	body, _, found := strings.CutLast(rest, "}")
	if !ok || !found {
		return 0, 0, nil
	}
	for _, tok := range strings.FieldsFunc(body, func(r rune) bool {
		return r == ',' || r == ' ' || r == '\t' || r == '\n' || r == '\r'
	}) {
		tok = strings.TrimSpace(tok)
		tok = strings.TrimPrefix(tok, "0x")
		tok = strings.TrimPrefix(tok, "0X")
		b, err := strconv.ParseUint(tok, 16, 8)
		if err != nil {
			continue
		}
		bits = append(bits, byte(b))
	}
	return w, h, bits
}

