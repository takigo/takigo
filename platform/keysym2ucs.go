package platform

// KeySymToRune converts a KeySym to a Unicode rune.
// Returns 0 if the keysym has no printable representation.
func KeySymToRune(ks KeySym) rune {
	// ASCII range.
	if ks >= 0x0020 && ks <= 0x007e {
		return rune(ks)
	}
	// Latin-1 supplement.
	if ks >= 0x00a0 && ks <= 0x00ff {
		return rune(ks)
	}
	// XKB Unicode keysyms: 0x01000000 + Unicode code point.
	if ks >= 0x01000000 && ks <= 0x0110ffff {
		return rune(ks & 0x00ffffff)
	}
	// Lookup table for legacy keysym ranges (Cyrillic, Greek, etc.).
	if r, ok := keysymToUCS[ks]; ok {
		return r
	}
	return 0
}

// RuneToKeySym returns the keysym for a printable character: Latin-1
// characters are their own keysym and anything else uses the Unicode
// keysym range (0x01000000 + code point), as XKB and Tk do. It returns 0
// for control characters and invalid runes.
func RuneToKeySym(r rune) KeySym {
	switch {
	case r >= 0x20 && r <= 0x7e, r >= 0xa0 && r <= 0xff:
		return KeySym(r)
	case r > 0xff && r <= 0x10ffff && (r < 0xd800 || r > 0xdfff):
		return KeySym(0x01000000 | r)
	}
	return 0
}

