package color

// NamedColor holds 16-bit RGB for a named color.
type NamedColor struct {
	R, G, B uint16
}

// rgb8 creates a NamedColor from 8-bit RGB values.
func rgb8(r, g, b uint8) NamedColor {
	return NamedColor{uint16(r) << 8, uint16(g) << 8, uint16(b) << 8}
}

